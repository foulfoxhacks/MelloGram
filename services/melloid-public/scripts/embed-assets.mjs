// Builds src/embedded-assets.js from public/: every static file inlined as
// base64 with its content type. Used by wrangler.embedded.toml for deploys
// that cannot use Workers Static Assets (e.g. behind a credential-injecting
// proxy, which breaks the asset-upload session token). Output is gitignored.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const PUBLIC = join(ROOT, "public");
const TYPES = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".wasm": "application/wasm", ".png": "image/png", ".svg": "image/svg+xml", ".ico": "image/x-icon",
  ".json": "application/json; charset=utf-8", ".txt": "text/plain; charset=utf-8", ".webp": "image/webp",
};
const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));
const files = {};
for (const file of walk(PUBLIC)) {
  const type = TYPES[extname(file)];
  if (!type) throw new Error(`no content type for ${file}`);
  files["/" + relative(PUBLIC, file).split("\\").join("/")] = { type, b64: readFileSync(file).toString("base64") };
}
writeFileSync(join(ROOT, "src/embedded-assets.js"), `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport default ${JSON.stringify(files)};\n`);
console.log(`embedded ${Object.keys(files).length} files`);
